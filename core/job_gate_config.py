def adjacent_id_pairs():
    """'사용' 상태인 쌍의 직무군 ID 두 개. 방향이 없으므로 frozenset으로 돌려준다 (4-1)."""
    result = {}
    for a, b, overlap, status in ADJACENT_PAIRS:
        if status == "사용":
            result[frozenset((PAIR_NAME_TO_ID[a], PAIR_NAME_TO_ID[b]))] = overlap
    return result


def is_adjacent(family_a, family_b):
    """두 직무군 ID가 '사용' 상태의 인접 쌍인지. 같은 직무군은 인접이 아니라 일치다."""
    return frozenset((family_a, family_b)) in adjacent_id_pairs()
